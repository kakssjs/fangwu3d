export function buildBlenderCyclesScript(fileName: string, preset: MaterialPreset) {
  return `# Blender Cycles setup generated by I Renovation
import bpy
from pathlib import Path

blend_dir = Path(bpy.path.abspath('//'))
glb_path = blend_dir / '${fileName}'
if not glb_path.exists():
    raise FileNotFoundError(f'Missing GLB: {glb_path}')

# Start from a clean scene.
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)

bpy.ops.import_scene.gltf(filepath=str(glb_path))

scene = bpy.context.scene
scene.render.engine = 'CYCLES'
scene.cycles.samples = 256
scene.cycles.use_denoising = True
scene.render.resolution_percentage = 100
scene.render.image_settings.file_format = 'PNG'
scene.render.filepath = str(blend_dir / 'renovation-cycles.png')
scene.world.color = (${parseInt(preset.background.slice(1, 3), 16) / 255}, ${parseInt(preset.background.slice(3, 5), 16) / 255}, ${parseInt(preset.background.slice(5, 7), 16) / 255})

# Soft studio lighting for interior product renders.
bpy.ops.object.light_add(type='AREA', location=(0, -6, 8))
key = bpy.context.object
key.name = 'I-Renovation Key'
key.data.energy = 1200
key.data.shape = 'RECTANGLE'
key.data.size = 8
key.data.size_y = 8
key.rotation_euler = (0.45, 0, 0)

bpy.ops.object.light_add(type='AREA', location=(6, 4, 5))
fill = bpy.context.object
fill.name = 'I-Renovation Fill'
fill.data.energy = 650
fill.data.size = 6
fill.rotation_euler = (0.8, 0, 2.4)

# Keep imported camera if present, otherwise add a presentation camera.
if not any(obj.type == 'CAMERA' for obj in bpy.data.objects):
    bpy.ops.object.camera_add(location=(10, -12, 9), rotation=(1.02, 0, 0.68))
    scene.camera = bpy.context.object

print('I Renovation Cycles scene ready:', glb_path)
`;
}

export function buildBlenderBatchScript() {
  return `# Run with: blender --background --python fangwu3d-blender-batch.py -- --jobs ./exports
import argparse, json, sys
from pathlib import Path
import bpy
from mathutils import Vector

def args():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    p = argparse.ArgumentParser(); p.add_argument('--jobs', default='exports'); p.add_argument('--samples', type=int, default=256); p.add_argument('--output-name', default='render.png'); return p.parse_args(argv)
def point_at(obj, target):
    obj.rotation_euler = (Vector(target) - obj.location).to_track_quat('-Z', 'Y').to_euler()
def render_job(job_dir, samples, output_name):
    glbs = sorted(job_dir.glob('*.glb'))
    if not glbs: return
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    bpy.ops.import_scene.gltf(filepath=str(glbs[0]))
    scene = bpy.context.scene; scene.render.engine = 'CYCLES'; scene.cycles.samples = samples; scene.cycles.use_denoising = True
    scene.render.image_settings.file_format = 'PNG'; scene.render.filepath = str(job_dir / output_name)
    job = json.loads((job_dir / 'job.json').read_text(encoding='utf-8')) if (job_dir / 'job.json').exists() else {}
    cam_data = bpy.data.cameras.new('Camera'); cam = bpy.data.objects.new('Camera', cam_data); scene.collection.objects.link(cam); scene.camera = cam
    cfg = job.get('camera', {}); cam.location = cfg.get('location', [9.5, -11.5, 8.5]); point_at(cam, cfg.get('target', [0, 0, 1])); cam_data.lens = cfg.get('lens', 42)
    bpy.ops.render.render(write_still=True)
def main():
    a = args(); root = Path(a.jobs).resolve(); dirs = [p for p in sorted(root.iterdir()) if p.is_dir()] or [root]
    for d in dirs: render_job(d, a.samples, a.output_name)
if __name__ == '__main__': main()
`;
}

export function buildBlenderJob(plan: PlanGeometry, preset: MaterialPreset) {
  return {
    schema: 'i-renovation-blender-job@1',
    source: 'scene_model',
    render: {
      engine: 'CYCLES',
      samples: 256,
      denoising: true,
      output: 'render.png',
      resolution: [3840, 2160],
    },
    camera: {
      location: [plan.width * 0.85, -plan.depth * 0.95, plan.wallHeight * 2.3],
      target: [plan.width / 2, 1.0, plan.depth / 2],
      lens: 42,
    },
    materials: preset,
    bounds: { width: plan.width, depth: plan.depth, wallHeight: plan.wallHeight },
  };
}

